export function labsCopy(locale) {
  const copy = resolveLocaleCopy({ zh, en, ja }, locale);
  copy.clearDraft = resolveLocaleCopy(
    { zh: '清空草稿', ja: '下書きをクリア', en: 'Clear draft' },
    locale,
  );
  copy.entryKinds = resolveLocaleCopy(
    {
      zh: {
        events: '活动',
        artists: '艺人',
        songs: '歌曲',
        albums: '专辑',
        projects: '企划',
        logs: '站务记录',
      },
      ja: {
        events: 'イベント',
        artists: 'アーティスト',
        songs: '楽曲',
        albums: 'アルバム',
        projects: '企画',
        logs: 'サイト更新',
      },
      en: {
        events: 'Event',
        artists: 'Artist',
        songs: 'Song',
        albums: 'Album',
        projects: 'Project',
        logs: 'Archive update',
      },
    },
    locale,
  );
  Object.assign(copy.entryKinds,Object.fromEntries(entityTypes.map(type=>[type,entityLabel(type,locale)])),{database:entityLabel('person',locale),articles:entityLabel('editorial-article',locale)});
  Object.assign(copy.kinds,copy.entryKinds);
  return { ...copy, ...personalToolsCopy(locale), path: relationPathCopy(locale) };
}
