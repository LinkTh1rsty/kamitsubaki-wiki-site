import {readFile,writeFile,mkdir,stat} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {installDetailsMotion} from '../src/lib/detailsMotion.mjs';

const source=resolve('public/ui-tokens.css');
const target=resolve('../kamitsubaki-wiki-site-backend/src/generatedUiTokens.js');
const sourceText=(await readFile(source,'utf8')).replaceAll('\r\n','\n');
const css=sourceText.trim();
const version=createHash('sha256').update(sourceText).digest('hex').slice(0,12);
const output=`// Generated from kamitsubaki-wiki-site/public/ui-tokens.css. Run pnpm ui:tokens:sync.\nexport const generatedUiTokens=${JSON.stringify(css)};\n`;
const check=process.argv.includes('--check');
for(const path of ['public/games/memory-corridor/index.html','public/games/kamitsubaki-explorer/index.html']){
  const file=resolve(path);
  const current=await readFile(file,'utf8');
  if(!current.includes('href="/ui-tokens.css'))throw Error(`Missing UI tokens stylesheet: ${path}`);
  const updated=current.replace(/href="\/ui-tokens\.css(?:\?v=[^"]*)?"/g,`href="/ui-tokens.css?v=${version}"`);
  if(check&&updated!==current){console.error(`Game UI tokens URL is stale: ${path}`);process.exitCode=1;}
  else if(!check&&updated!==current)await writeFile(file,updated);
}
if(check){
  const current=await readFile(target,'utf8').catch(()=>null);
  if(current===null){console.log('Backend checkout unavailable; frontend token source is present. Run this check again beside the backend checkout before release.');}
  else if(current!==output){console.error('Frontend and Worker UI tokens differ. Run pnpm ui:tokens:sync.');process.exitCode=1;}
  else console.log('Frontend and Worker UI tokens match.');
}else{
  await writeFile(target,output);
  console.log('Updated Worker UI token snapshot and static game URLs.');
}

const motionTarget=resolve('../kamitsubaki-wiki-site-backend/src/generatedDetailsMotion.js');
const motionOutput=`// Generated from the frontend detailsMotion.mjs by pnpm ui:tokens:sync.\nexport const installDetailsMotion=${installDetailsMotion.toString()};\n`;
if(check){const current=await readFile(motionTarget,'utf8').catch(()=>null);if(current!==null&&current!==motionOutput){console.error('Shared disclosure runtime is stale. Run pnpm ui:tokens:sync.');process.exitCode=1;}}
else await writeFile(motionTarget,motionOutput);

// The same font bytes are served by Pages and the standalone Worker console.
const backendExists=await stat(resolve('../kamitsubaki-wiki-site-backend/src')).then(()=>true).catch(()=>false);
const fontBytes=await readFile(resolve('node_modules/@fontsource-variable/jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2'));
const fontPath='/fonts/jetbrains-mono-latin-5.3.0.woff2';
const fontHash=createHash('sha256').update(fontBytes).digest('hex');
const fontModule=`// Generated by pnpm ui:tokens:sync. JetBrains Mono 5.3.0, SIL OFL; see licenses/JetBrainsMono-OFL.txt.\nexport const terminalFontPath=${JSON.stringify(fontPath)};\nexport const terminalFontETag='"${fontHash}"';\nconst data=${JSON.stringify(fontBytes.toString('base64'))};\nlet bytes;\nexport function terminalFontBytes(){return bytes||=(Uint8Array.from(atob(data),c=>c.charCodeAt(0)));}\n`;
const license=await readFile(resolve('node_modules/@fontsource-variable/jetbrains-mono/LICENSE'));
for(const [file,expected] of [[resolve('public'+fontPath),fontBytes],[resolve('public/fonts/JetBrainsMono-OFL.txt'),license],[resolve('../kamitsubaki-wiki-site-backend/licenses/JetBrainsMono-OFL.txt'),license],[resolve('../kamitsubaki-wiki-site-backend/src/generatedTerminalFont.js'),Buffer.from(fontModule)]]){
 if(check&&!backendExists&&file.startsWith(resolve('../kamitsubaki-wiki-site-backend')))continue;
 if(check){const actual=await readFile(file).catch(()=>null);const matches=actual && (file.endsWith('JetBrainsMono-OFL.txt')?actual.toString('utf8').replaceAll('\r\n','\n')===expected.toString('utf8').replaceAll('\r\n','\n'):actual.equals(expected));if(!matches){console.error('Terminal font artifact is stale: '+file);process.exitCode=1;}}
 else{await mkdir(resolve(file,'..'),{recursive:true});await writeFile(file,expected);}
}
